COPY INTO ENERGY_LAB.BRONZE.EVENT_LEDGER
 (EVENT_ID, PROVIDER, TECHNOLOGY, INTERVAL_UTC, REVISION_RAW,
  ENERGY_RAW, OPERATION, SOURCE_FILE, SOURCE_ROW, LOADED_AT)
FROM (
 SELECT t.$1,t.$2,t.$3,t.$4,t.$5,t.$6,t.$7,
        METADATA$FILENAME,METADATA$FILE_ROW_NUMBER,
        METADATA$START_SCAN_TIME
 FROM @ENERGY_LAB.BRONZE.STG_EVENT_CSV t
)
FILE_FORMAT=(FORMAT_NAME=ENERGY_LAB.BRONZE.FF_EVENT_CSV)
ON_ERROR=ABORT_STATEMENT;

CREATE OR REPLACE VIEW ENERGY_LAB.SILVER.V_VALID_EVENTS AS
SELECT EVENT_ID,PROVIDER,TECHNOLOGY,INTERVAL_UTC,
 TRY_TO_NUMBER(REVISION_RAW) AS REVISION,
 TRY_TO_DECIMAL(ENERGY_RAW,18,3) AS ENERGY_MWH,
 OPERATION
FROM ENERGY_LAB.BRONZE.EVENT_LEDGER
WHERE EVENT_ID IS NOT NULL AND PROVIDER IS NOT NULL
 AND TECHNOLOGY IS NOT NULL
 AND INTERVAL_UTC LIKE '____-__-__T__:__:__Z'
 AND TRY_TO_TIMESTAMP_TZ(INTERVAL_UTC) IS NOT NULL
 AND TRY_TO_NUMBER(REVISION_RAW)>0
 AND TRY_TO_DECIMAL(ENERGY_RAW,18,3)>=0
 AND OPERATION IN ('UPSERT','DELETE')
 AND (OPERATION <> 'DELETE' OR TRY_TO_DECIMAL(ENERGY_RAW,18,3)=0);

-- The conflict guard is mandatory before any published view is trusted.
-- A result row means release BLOCKED (same key and revision, different payload).
SELECT PROVIDER,TECHNOLOGY,INTERVAL_UTC,REVISION,
 COUNT(DISTINCT CONCAT(OPERATION,':',TO_VARCHAR(ENERGY_MWH))) AS distinct_payloads
FROM ENERGY_LAB.SILVER.V_VALID_EVENTS
GROUP BY 1,2,3,4 HAVING distinct_payloads>1;

CREATE OR REPLACE VIEW ENERGY_LAB.GOLD.FCT_ENERGY_HOURLY AS
WITH unique_deliveries AS (
 SELECT DISTINCT EVENT_ID,PROVIDER,TECHNOLOGY,INTERVAL_UTC,
                 REVISION,ENERGY_MWH,OPERATION
 FROM ENERGY_LAB.SILVER.V_VALID_EVENTS
), current_rows AS (
 SELECT * FROM unique_deliveries
 QUALIFY ROW_NUMBER() OVER (
   PARTITION BY PROVIDER,TECHNOLOGY,INTERVAL_UTC
   ORDER BY REVISION DESC,EVENT_ID DESC
 )=1
)
SELECT PROVIDER,TECHNOLOGY,INTERVAL_UTC,REVISION,ENERGY_MWH
FROM current_rows WHERE OPERATION='UPSERT';
