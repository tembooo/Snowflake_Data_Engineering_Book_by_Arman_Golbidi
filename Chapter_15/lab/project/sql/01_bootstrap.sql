CREATE TABLE IF NOT EXISTS ENERGY_LAB.BRONZE.EVENT_LEDGER (
 EVENT_ID VARCHAR, PROVIDER VARCHAR, TECHNOLOGY VARCHAR,
 INTERVAL_UTC VARCHAR, REVISION_RAW VARCHAR, ENERGY_RAW VARCHAR,
 OPERATION VARCHAR, SOURCE_FILE VARCHAR, SOURCE_ROW NUMBER,
 LOADED_AT TIMESTAMP_LTZ
);
CREATE OR REPLACE FILE FORMAT ENERGY_LAB.BRONZE.FF_EVENT_CSV
 TYPE=CSV FIELD_OPTIONALLY_ENCLOSED_BY='"' SKIP_HEADER=1
 EMPTY_FIELD_AS_NULL=TRUE ERROR_ON_COLUMN_COUNT_MISMATCH=TRUE;
CREATE STAGE IF NOT EXISTS ENERGY_LAB.BRONZE.STG_EVENT_CSV
 FILE_FORMAT=ENERGY_LAB.BRONZE.FF_EVENT_CSV;
